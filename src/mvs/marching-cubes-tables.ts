/** The triangles of each case as edge indices, 16 per case, `-1` after the last (the layout of Bourke's table). */
export const MC_TRI_TABLE: Int8Array = (() => {
  const table = new Int8Array(256 * 16).fill(-1);
  MC_CASE_TRIANGLES.forEach((row, c) => {
    for (let k = 0; k < row.length; k++) table[c * 16 + k] = parseInt(row[k]!, 16);
  });
  return table;
})();
